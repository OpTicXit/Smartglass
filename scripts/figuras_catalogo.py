def svg(hue, cuerpo, oscuros, brillos):
    formas = "".join(f'<path d="{d}"/>' for d in cuerpo)
    negro = "".join(f'<path d="{d}"/>' for d in oscuros)
    luces = "".join(f'<path d="{d}"/>' for d in brillos)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600">
<defs>
<radialGradient id="f" cx="50%" cy="36%" r="78%"><stop offset="0" stop-color="hsl({hue} 42% 24%)"/><stop offset=".62" stop-color="hsl({hue} 44% 11%)"/><stop offset="1" stop-color="hsl({hue} 50% 6%)"/></radialGradient>
<linearGradient id="v" x1=".15" y1="0" x2=".85" y2="1"><stop offset="0" stop-color="hsl({hue} 90% 94%)"/><stop offset=".38" stop-color="hsl({hue} 85% 70%)"/><stop offset=".72" stop-color="hsl({hue} 80% 46%)"/><stop offset="1" stop-color="hsl({hue} 90% 78%)"/></linearGradient>
<radialGradient id="s"><stop offset="0" stop-color="hsl({hue} 90% 70%)" stop-opacity=".5"/><stop offset="1" stop-color="hsl({hue} 90% 70%)" stop-opacity="0"/></radialGradient>
</defs>
<rect width="800" height="600" fill="url(#f)"/>
<ellipse cx="400" cy="500" rx="260" ry="34" fill="url(#s)"/>
<g fill="url(#v)" opacity=".86" stroke="hsl({hue} 95% 92%)" stroke-width="3" stroke-linejoin="round">{formas}</g>
<g fill="hsl({hue} 60% 12%)" opacity=".8">{negro}</g>
<g fill="none" stroke="#fff" stroke-opacity=".62" stroke-width="4" stroke-linecap="round" stroke-linejoin="round">{luces}</g>
</svg>
"""


